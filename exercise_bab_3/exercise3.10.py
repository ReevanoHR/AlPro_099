players = ["Lionel Messi", "Cristiano Ronaldo", "Neymar", "Kylian Mbappe", "Erling Haaland"]

print("Original list:")
print(players)
print("\nFavorite player:")
print(players[0])
# nambahin list baru di akhir pake append()
players.append("Lamine Yamal")
print("\nAfter append:")
print(players)
#memasukkan list baru di index tertentu pake insert()
players.insert(2, "Jude Bellingham")
print("\nAfter insert:")
print(players)
# menghapus list tertentu pake del()
del players[1]
print("\nAfter del:")
print(players)
# menghapus list NGACAK pake pop()
removed_player = players.pop()
print(f"\nPopped player: {removed_player}")
print(players)
# menghapus list tertentu pake remove()
players.remove("Neymar")
print("\nAfter remove:")
print(players)
# menampilkan list secara abjad sementara pake sorted()
print("\nTemporary alphabetical order:")
print(sorted(players))
#Ngecek List masih sama atau tidak
print("\nOriginal list:")
print(players)
# reverse() untuk membalik urutan list secara permanen
players.reverse()
print("\nReversed list:")
print(players)
# Mengurutkan kembali ke urutan asli
players.sort()
print("\nSorted permanently:")
print(players)
# Urutan secara terbalik permanen
players.sort(reverse=True)
print("\nReverse alphabetical order:")
print(players)
# Jumlah Player
print(f"\nNumber of players in the list: {len(players)}")